-- Let's write standard Supabase Auth RLS policies:
CREATE POLICY "Users can view own record" ON public.users FOR SELECT USING (
    id = auth.uid() OR 
    EXISTS (SELECT 1 FROM public.users u WHERE u.id = auth.uid() AND u.role = 'admin')
);

CREATE POLICY "Users can update own record" ON public.users FOR UPDATE USING (
    id = auth.uid()
);

CREATE POLICY "Users can view assigned tasks" ON public.tasks FOR SELECT USING (
    assigned_to = auth.uid() OR created_by = auth.uid() OR
    EXISTS (SELECT 1 FROM public.users u WHERE u.id = auth.uid() AND u.role = 'admin')
);

CREATE POLICY "Users can view own generated images" ON public.generated_images FOR SELECT USING (
    task_id IN (SELECT id FROM public.tasks WHERE assigned_to = auth.uid() OR created_by = auth.uid()) OR
    EXISTS (SELECT 1 FROM public.users u WHERE u.id = auth.uid() AND u.role = 'admin')
);

CREATE POLICY "Users can insert own generated images" ON public.generated_images FOR INSERT WITH CHECK (
    task_id IN (SELECT id FROM public.tasks WHERE assigned_to = auth.uid())
);

CREATE POLICY "Users can update own generated images" ON public.generated_images FOR UPDATE USING (
    task_id IN (SELECT id FROM public.tasks WHERE assigned_to = auth.uid())
);

